-- ---- 自己テスト
selfTest :: [(String, Bool)]
selfTest =
  [ ("自動販売機：長さ 6 までの全部の入力列 " ++ show nSeq ++ " 通りで「入れた = ジュース × " ++ show price ++ " + おつり + 残り」", okCons && nSeq == 5461)
  , ("金額は 0〜90 円の 10 状態にとどまる、おつりは負にならない", okRange && vendN == 10 && all (all (\(_, (t, _)) -> t >= 0)) vendTr)
  , ("ジュースは「入れた合計が 100 円以上になった瞬間」にだけ出る", okDrink)
  , ("例：50 → 50 でジュース、100 → 返却 は「ジュースが出て返却 0 円」、90 円 + 100 円 → おつり 90 円"
    , oDrink (snd (vendLook 5 "50")) && oChange (snd (vendLook 5 "50")) == 0 && fst (vendLook 0 "100") == 0 && oChange (snd (vendLook 0 "R")) == 0 && oChange (snd (vendLook 9 "100")) == 90)
  , ("信号機：車が青・黄のときは歩行者は必ず赤（全部の状態の出力を調べる）", all (\(c, p) -> not (c /= 'R' && p /= 'R')) sigOut)
  , ("ボタンを押せば、どの状態からでも時間切れ 2 回以内に「歩 青」になる（点滅中を除く）", okReach)
  , ("ボタンを押さなければ、車はずっと青のまま（t を 50 回）", iterate (`sigNext` 't') 0 !! 50 == 0) ]
  where
    -- 長さ 0〜6 のすべての入力列（4 種類 → 5461 通り）
    seqs = concat (take 7 (iterate (\l -> [ s ++ [c] | s <- l, c <- vendAlpha ]) [[]]))
    nSeq = length seqs
    results = map runSeq seqs
    okCons = all (\(a, _, _) -> a) results
    okRange = all (\(_, b, _) -> b) results
    okDrink = all (\(_, _, c) -> c) results
    -- 1 つの入力列：(お金の保存, 範囲, ジュースの出かた)
    runSeq sq =
      let go (!q, !ins, !dr, !ch, !since, !rng, !drk) c =
            let (t, o) = vendLook q c
                coin = if c /= "R" then read c else 0
                since1 = since + coin
                drk1 = drk && not (oDrink o && since1 < price) && not (not (oDrink o) && c /= "R" && since1 >= price)
                since2 = if oDrink o || c == "R" then 0 else since1
            in (t, ins + coin, dr + (if oDrink o then 1 else 0), ch + oChange o, since2, rng && t >= 0 && t < vendN && oChange o >= 0, drk1)
          (qf, insf, drf, chf, _, rngf, drkf) = foldl' go (0 :: Int, 0 :: Int, 0 :: Int, 0 :: Int, 0 :: Int, True, True) sq
      in (insf == drf * price + chf + qf * 10, rngf, drkf)
    okReach = and [ q0 == 3 || q0 == 4 || (q == 3 && k <= 2)
                  | q0 <- [0 .. 4]
                  , let walk q1 k1 = if q1 /= 3 && k1 < 6 then walk (sigNext q1 't') (k1 + 1) else (q1, k1)
                  , let (q, k) = walk (sigNext q0 'b') (0 :: Int) ]

