price :: Int
price = 100                                   -- ★ ジュースの値段（10 円単位。状態の数 = price / 10）

coins :: [Int]
coins = [10, 50, 100]                         -- ★ 入れられるお金

lightSec :: [Float]
lightSec = [3, 1.5, 1.2, 3, 1.5]              -- ★ 信号の各状態の長さ（秒）。0 番は「最低これだけ青」

sigNames :: [String]
sigNames = ["car G", "pushed", "car Y", "walk G", "blink"]   -- 車 青・車 青（押された）・車 黄・歩 青・歩 点滅

sigOut :: [(Char, Char)]                      -- ムーア型の出力 (車, 歩行者)（B = 点滅）
sigOut = [('G', 'R'), ('G', 'R'), ('Y', 'R'), ('R', 'G'), ('R', 'B')]

-- ---- 自動販売機（ミーリー型）：状態 = 入っている金額。表 vendTr !! 状態 = [(入力, (次の状態, 出力))]
data Out = Out { oDrink :: !Bool, oChange :: !Int }

-- ★ 1 つの入力で：返却なら全部返す、足りたらジュースとおつり、足りなければためる
vendStep :: Int -> String -> (Int, Out)
vendStep c inp
  | inp == "R" = (0, Out False c)
  | t >= price = (0, Out True (t - price))
  | otherwise = (t, Out False 0)
  where t = c + read inp

vendAlpha :: [String]
vendAlpha = map show coins ++ ["R"]

vendN :: Int
vendN = price `div` 10

vendTr :: [[(String, (Int, Out))]]
vendTr = [ [ (c, let (t, o) = vendStep (q * 10) c in (t `div` 10, o)) | c <- vendAlpha ] | q <- [0 .. vendN - 1] ]

vendLook :: Int -> String -> (Int, Out)
vendLook q c = maybe (0, Out False 0) id (lookup c (at' vendTr q []))

-- ---- 信号機（ムーア型）：入力 b = ボタン、t = 時間切れ。出力は状態で決まる（sigOut）
sigTr :: [[(Char, Int)]]
sigTr = [[('b', 1), ('t', 0)], [('b', 1), ('t', 2)], [('b', 2), ('t', 3)], [('b', 3), ('t', 4)], [('b', 4), ('t', 0)]]

sigNext :: Int -> Char -> Int
sigNext q c = maybe q id (lookup c (at' sigTr q []))

data Flash = Flash { fFrom :: !Int, fTo :: !Int, fIn :: String, fOut :: Out, fLife :: !Int }

data World = World
  { wCredit  :: !Int                          -- 入っている金額
  , wLastV   :: Maybe Flash                   -- さっきの自動販売機の遷移
  , wLog     :: [String]
  , wDrinks  :: !Int
  , wChange  :: !Int
  , wInserted :: !Int
  , wSigQ    :: !Int                          -- 信号機の状態
  , wSigT    :: !Float                        -- この状態になってからの秒数
  , wLastS   :: Maybe Flash
  , wTest    :: [(String, Bool)] }

