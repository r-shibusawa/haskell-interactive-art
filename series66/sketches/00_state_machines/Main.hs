event :: Env -> Event -> World -> IO World
event env ev w = pure $ case ev of
  EventKey (MouseButton LeftButton) Down _ p -> pressAt (toP5 env p) w
  EventKey (Char c) Down _ _
    | c == '1' -> insert "10" w
    | c == '2' -> insert "50" w
    | c == '3' -> insert "100" w
    | isKey 'r' c -> insert "R" w
    | isKey 'b' c -> signalInput 'b' w
  _ -> w
  where
    pressAt (x, y) w0 = foldl' (\wa (k, _, bx, by) -> if x > bx && x < bx + 108 && y > by && y < by + 32
                                                        then (if k == "b" then signalInput 'b' wa else insert k wa) else wa) w0 (buttons env)

