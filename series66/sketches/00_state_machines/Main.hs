world0 :: World
world0 = World 0 Nothing [] 0 0 0 0 0 Nothing []

insert :: String -> World -> World
insert c w =
  let q = wCredit w `div` 10
      (t, o) = vendLook q c
      coin = if c == "R" then "Return" else c ++ " yen"
      msg = coin ++ " -> " ++ (if oDrink o then "drink" else "")
            ++ (if oChange o > 0 then (if oDrink o then ", " else "") ++ "change " ++ show (oChange o) ++ " yen" else if oDrink o then "" else "(nothing)")
  in w { wLastV = Just (Flash q t c o 90)
       , wInserted = wInserted w + (if c /= "R" then read c else 0)
       , wDrinks = wDrinks w + (if oDrink o then 1 else 0)
       , wChange = wChange w + oChange o
       , wCredit = t * 10
       , wLog = take 6 (msg : wLog w) }

signalInput :: Char -> World -> World
signalInput c w =
  let t = sigNext (wSigQ w) c
  in w { wLastS = Just (Flash (wSigQ w) t [c] (Out False 0) 60), wSigT = if t /= wSigQ w then 0 else wSigT w, wSigQ = t }

-- 信号の時計：時間がたつと入力 t が来る
step :: Float -> World -> World
step dt w0 =
  let w1 = w0 { wSigT = wSigT w0 + dt }
      w2 = if wSigT w1 >= at' lightSec (wSigQ w1) 3 && wSigQ w1 /= 0 then signalInput 't' w1 else w1
      w3 = if wSigQ w2 == 0 then w2 { wSigT = min (wSigT w2) (at' lightSec 0 3) } else w2
      life = fmap (\f -> f { fLife = fLife f - 1 })
  in w3 { wLastV = life (wLastV w3), wLastS = life (wLastS w3) }

vendPos, sigPos :: Env -> [Pos]
vendPos env = circleLayout vendN (envW env * 0.26) (envH env * 0.5) (radOf env) (-pi / 2)
sigPos env = circleLayout 5 (envW env * 0.7) (envH env * 0.5) (radOf env * 0.85) pi

radOf :: Env -> Float
radOf env = min (envW env * 0.18) (envH env * 0.27)

flashHi :: Maybe Flash -> RGB -> Edge -> Maybe RGB
flashHi fl c e = case fl of
  Just f | fLife f > 0 && eFrom e == fFrom f && eTo e == fTo f -> Just c
  _ -> Nothing

buttons :: Env -> [(String, String, Float, Float)]   -- (入力, 文字, x, y)。大きさは 108 × 32
buttons env = [ (k, lab, 30 + i2f i * 118, envH env - 46) | (i, (k, lab)) <- zip [0 :: Int ..] [("10", "10 yen"), ("50", "50 yen"), ("100", "100 yen"), ("R", "Return"), ("b", "Button")] ]

